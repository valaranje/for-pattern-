"""
Задача 04-07. Сколько гласных

Прочитайте строку и выведите количество гласных букв в ней (без учёта
регистра). Гласные: а, е, ё, и, о, у, ы, э, ю, я.

Пример
------
Ввод:
Привет, мир!
Вывод:
3
"""

VOWELS = "аеёиоуыэюя"

# TODO: переберите символы строки в нижнем регистре и посчитайте гласные

s = input().lower()
print(sum(1 for ch in s if ch in VOWELS))