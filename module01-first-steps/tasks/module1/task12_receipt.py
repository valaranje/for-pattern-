"""
Задача 12. Чек со скидкой

Кассовый чек. Прочитайте три числа, каждое с отдельной строки:

1. цену товара (дробное число, рубли);
2. количество (целое);
3. скидку в процентах (целое, от 0 до 100).

Выведите три строки (все суммы округлены до 2 знаков):

    Стоимость: <цена * количество>
    Скидка: <стоимость * процент / 100>
    К оплате: <стоимость − скидка>

Пример
------
Ввод:
19.99
7
12
Вывод:
Стоимость: 139.93
Скидка: 16.79
К оплате: 123.14
"""

# TODO: прочитайте цену, количество и процент скидки
price = float(input())
qant = int(input())
discount = int(input())
# TODO: вычислите и выведите три строки чека
Cost = price * qant
Discount = (Cost * discount)/100
Oplata = Cost - Discount

print(f'Стоимость:{Cost:.2f}')
print(f'Скидка:{Discount:.2f}')
print(f'К оплате:{Oplata:.2f}')